import 'dart:convert';

import '../entities/place.dart';
import '../entities/place_source.dart';

/// What a scanned QR code points at.
sealed class QrTarget {
  const QrTarget();
}

/// Reference to a place in one of the sources (resolved via repository).
class QrPlaceRef extends QrTarget {
  const QrPlaceRef(this.source, this.sourceId);
  final PlaceSource source;
  final String sourceId;

  String get placeId => '${source.name}:$sourceId';

  @override
  bool operator ==(Object other) => other is QrPlaceRef && other.source == source && other.sourceId == sourceId;

  @override
  int get hashCode => Object.hash(source, sourceId);

  @override
  String toString() => 'QrPlaceRef($placeId)';
}

/// Self-contained place encoded as JSON in the QR itself (works offline).
class QrInlinePlace extends QrTarget {
  const QrInlinePlace(this.place);
  final Place place;
}

/// Any other web link — offered to open in the browser.
class QrExternalLink extends QrTarget {
  const QrExternalLink(this.uri);
  final Uri uri;
}

/// Unrecognised content.
class QrUnknown extends QrTarget {
  const QrUnknown(this.raw);
  final String raw;
}

/// Turns raw QR text into a [QrTarget]. Pure and fully unit-tested.
///
/// Supported formats:
///  * `qstory:<source>:<id>` and `qstory://place/<source>/<id>`
///  * Wikipedia article URLs (`https://ru.wikipedia.org/wiki/Title`, `?curid=`)
///  * Wikidata item URLs (`https://www.wikidata.org/wiki/Q123`)
///  * OpenStreetMap URLs (`https://www.openstreetmap.org/node/123`)
///  * PastVu photo URLs (`https://pastvu.com/p/123`)
///  * JSON `{ "title": ..., "lat": ..., "lon": ..., "description": ... }`
abstract final class QrPayloadParser {
  static QrTarget parse(String raw) {
    final text = raw.trim();
    if (text.isEmpty) return QrUnknown(raw);

    if (text.startsWith('{')) {
      final inline = _parseJson(text);
      if (inline != null) return inline;
    }

    final scheme = _parseScheme(text);
    if (scheme != null) return scheme;

    final uri = Uri.tryParse(text);
    if (uri != null && (uri.scheme == 'http' || uri.scheme == 'https') && uri.host.isNotEmpty) {
      return _parseUrl(uri) ?? QrExternalLink(uri);
    }
    return QrUnknown(raw);
  }

  static QrTarget? _parseScheme(String text) {
    // qstory:wikipedia:ru:123  |  qstory://place/osm/node/1
    final m1 = RegExp(r'^qstory:(?!//)([a-z]+):(.+)$').firstMatch(text);
    final m2 = RegExp(r'^qstory://place/([a-z]+)/(.+)$').firstMatch(text);
    final m = m1 ?? m2;
    if (m == null) return null;
    final source = PlaceSource.values.where((s) => s.name == m.group(1)).firstOrNull;
    if (source == null) return null;
    return QrPlaceRef(source, Uri.decodeComponent(m.group(2)!));
  }

  static QrTarget? _parseUrl(Uri uri) {
    final host = uri.host.toLowerCase();
    final segs = uri.pathSegments.where((s) => s.isNotEmpty).toList();

    final wiki = RegExp(r'^([a-z\-]+)\.(?:m\.)?wikipedia\.org$').firstMatch(host);
    if (wiki != null) {
      final lang = wiki.group(1)!;
      final curid = uri.queryParameters['curid'];
      if (curid != null && int.tryParse(curid) != null) {
        return QrPlaceRef(PlaceSource.wikipedia, '$lang:$curid');
      }
      if (segs.length >= 2 && segs[0] == 'wiki') {
        final title = segs.sublist(1).join('/').replaceAll('_', ' ');
        return QrPlaceRef(PlaceSource.wikipedia, '$lang:$title');
      }
      return null;
    }

    if (host.endsWith('wikidata.org')) {
      final q = segs.lastWhere((s) => RegExp(r'^Q\d+$').hasMatch(s), orElse: () => '');
      return q.isEmpty ? null : QrPlaceRef(PlaceSource.wikidata, q);
    }

    if (host.endsWith('openstreetmap.org') && segs.length >= 2) {
      final type = segs[0];
      if ({'node', 'way', 'relation'}.contains(type) && int.tryParse(segs[1]) != null) {
        return QrPlaceRef(PlaceSource.osm, '$type/${segs[1]}');
      }
      return null;
    }

    if (host.endsWith('pastvu.com') && segs.length >= 2 && segs[0] == 'p') {
      return int.tryParse(segs[1]) != null ? QrPlaceRef(PlaceSource.pastvu, segs[1]) : null;
    }
    return null;
  }

  static QrTarget? _parseJson(String text) {
    try {
      final map = jsonDecode(text);
      if (map is! Map) return null;
      final title = map['title'];
      if (title is! String || title.trim().isEmpty) return null;
      // QR generated by QStory itself (Place.toJson) keeps its own id, so
      // scanning it matches the same favourite/visit; hand-written plaques
      // use "id" (or nothing) and get a stable "qr-" id.
      final ownId = map['source'] == PlaceSource.user.name ? map['sourceId']?.toString() : null;
      final id = (map['id'] ?? base64Url.encode(utf8.encode(title)).replaceAll('=', '')).toString();
      return QrInlinePlace(Place(
        source: PlaceSource.user,
        sourceId: ownId ?? 'qr-$id',
        title: title.trim(),
        lat: (map['lat'] as num?)?.toDouble() ?? 0,
        lon: (map['lon'] as num?)?.toDouble() ?? 0,
        summary: (map['summary'] ?? map['description'] ?? '').toString(),
        description: map['description']?.toString(),
        imageUrl: (map['imageUrl'] ?? map['image'])?.toString(),
        url: map['url']?.toString(),
        category: PlaceCategory.parse(map['category']?.toString()),
        yearStart: ((map['year'] ?? map['yearStart']) as num?)?.toInt(),
        yearEnd: (map['yearEnd'] as num?)?.toInt(),
        author: map['author']?.toString(),
      ));
    } catch (_) {
      return null;
    }
  }

  /// Payload to print on a plaque for the given place.
  static String encode(Place place) =>
      place.source == PlaceSource.user ? jsonEncode(place.toJson()) : 'qstory:${place.id}';
}
